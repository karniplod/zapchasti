"""Проверка вводимых данных — в одном месте.

Здесь правила формата: каким должен быть телефон, ФИО, адрес, VIN,
номер отслеживания, год машины. Роутеры только вызывают проверку и
отвечают 422 с её текстом; проверки «есть ли такое в базе» (категория,
модификация, дубль VIN) остаются в роутерах — это уже логика.

Те же правила в браузере — static/js/validation/rules.js (Check): форма
подсказывает сразу, а сервер проверяет ещё раз — скрипт можно выключить,
а запрос отправить в обход формы. Меняя правило здесь, меняйте и там.

    people   — телефон, email, логин, имя, ФИО, пароль
    address  — страна, индекс, улица, дом, корпус, квартира
    catalog  — детали и машины: состояние, тип, статусы, VIN, год, дата
    orders   — номер отслеживания посылки
    errors   — ошибки 422 от FastAPI по-русски и с названием поля

Проверка возвращает текст ошибки (или None), а там, где значение
приводится к одному виду, — пару (значение, ошибка).
"""

from fastapi import HTTPException


class FieldError(HTTPException):
    """Ошибка у конкретного поля формы: ответ {"detail", "errors": [{field, msg}]}
    — форма покажет её под полем (serverErrors в static/js/validation/form.js),
    а не всплывашкой. Обработчик — в app/main.py."""

    def __init__(self, field: str, msg: str, status: int = 422):
        super().__init__(status, msg)
        self.field = field


def require(err: str | None, status: int = 422) -> None:
    """Ошибка проверки → ответ 422 с её текстом."""
    if err:
        raise HTTPException(status, err)
