async def seed(dry_run: bool):
    st = {"p": 0, "c": 0, "skip": 0}
    async with SessionFactory() as s:
        for i, (parent, children) in enumerate(TREE.items()):
            row = (
                await s.execute(
                    text("""
                INSERT INTO part_categories (parent_id, name, slug, sort_order)
                VALUES (NULL, :n, :s, :o)
                ON CONFLICT (slug) DO UPDATE SET name = part_categories.name
                RETURNING id, (xmax = 0) AS ins
            """),
                    {"n": parent, "s": slugify(parent), "o": i},
                )
            ).first()
            if row.ins:
                st["p"] += 1
            for o, child in enumerate(children):
                r = (
                    await s.execute(
                        text("""
                    INSERT INTO part_categories (parent_id, name, slug, sort_order)
                    VALUES (:p, :n, :s, :o)
                    ON CONFLICT (slug) DO UPDATE SET name = part_categories.name
                    RETURNING (xmax = 0) AS ins
                """),
                        {
                            "p": row.id,
                            "n": child,
                            "s": slugify(f"{parent}-{child}"),
                            "o": o,
                        },
                    )
                ).first()
                st["c" if r.ins else "skip"] += 1
        if dry_run:
            await s.rollback()
            print("[ПРОБНЫЙ ЗАПУСК] Ничего не сохранено.")
        else:
            await s.commit()
    return st


async def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    print(f"Разделов: {len(TREE)}, узлов: {sum(len(v) for v in TREE.values())}")
    st = await seed(a.dry_run)
    print(f"Новых разделов: {st['p']}\nНовых узлов: {st['c']}\nУже было: {st['skip']}")


if __name__ == "__main__":
    asyncio.run(main())
