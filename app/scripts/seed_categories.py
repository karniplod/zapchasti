# Разделы Авито, в которые уходит объявление. Для узлов внутри
# «Для автомобилей» это сам раздел (Кузов, Двигатель…), для остальных —
# соседняя категория верхнего уровня (Шины диски и колёса и т.д.).
AVITO_SECTION_PARENTS = {"Для автомобилей", "Запчасти и аксессуары"}


def walk(node, path=()):
    """Отдаёт (путь, дети) для каждого узла дерева, сверху вниз."""
    if isinstance(node, dict):
        for name, children in node.items():
            yield path + (name,), children
            yield from walk(children, path + (name,))
    elif isinstance(node, list):
        for name in node:
            yield path + (name,), None


def avito_section(path: tuple[str, ...]) -> str | None:
    """Раздел площадки = узел, чей родитель — «Для автомобилей»
    или «Запчасти и аксессуары».

    Идём с конца: «Запчасти» сама лежит в «Запчасти и аксессуары», и
    поиск сверху останавливался бы на ней, приписывая всем деталям
    раздел «Запчасти» вместо «Кузов», «Двигатель» и прочих."""
    for i in range(len(path) - 1, 0, -1):
        if path[i - 1] in AVITO_SECTION_PARENTS:
            return path[i]
    return None


async def seed(dry_run: bool):
    st = {"new": 0, "existing": 0}
    ids: dict[tuple[str, ...], int] = {}

    async with SessionFactory() as s:
        for order, (path, _) in enumerate(walk(TREE)):
            parent_id = ids.get(path[:-1])
            row = (
                await s.execute(
                    text("""
                INSERT INTO part_categories (parent_id, name, slug, sort_order, avito_category)
                VALUES (:p, :n, :s, :o, :av)
                ON CONFLICT (slug) DO UPDATE
                    SET name = part_categories.name,
                        avito_category = COALESCE(part_categories.avito_category,
                                                  EXCLUDED.avito_category)
                RETURNING id, (xmax = 0) AS ins
            """),
                    {
                        "p": parent_id,
                        "n": path[-1],
                        # Слаг по всему пути: «Датчик» встречается в разных
                        # ветках, а slug уникален на всю таблицу
                        "s": slugify("-".join(path)),
                        "o": order,
                        "av": avito_section(path),
                    },
                )
            ).first()
            ids[path] = row.id
            st["new" if row.ins else "existing"] += 1

        if dry_run:
            await s.rollback()
            print("[ПРОБНЫЙ ЗАПУСК] Ничего не сохранено.")
        else:
            await s.commit()
    return st


async def main():
    ap = argparse.ArgumentParser(description="Дерево категорий запчастей в структуре Авито")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    nodes = list(walk(TREE))
    leaves = [p for p, children in nodes if not children]
    print(f"Узлов в дереве: {len(nodes)}, из них конечных: {len(leaves)}")

    st = await seed(a.dry_run)
    print(f"Создано: {st['new']}\nУже было: {st['existing']}")


if __name__ == "__main__":
    asyncio.run(main())
